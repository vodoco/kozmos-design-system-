// Run with node scripts/sync-ios-taxonomy.mjs [--write].
// The Pointr QA app reads the same version-pinned taxonomy projection the web
// POI examples use, so both platforms present a property the same way. The
// projection is generated into a Swift literal, as the POI fixtures are, so the
// app needs no second resource-loading path. Default is a freshness check.
import { readFile, writeFile } from "node:fs/promises";

const source = new URL(
  "../packages/react/src/components/POIDetailPanel/taxonomy-10.12.0.fixture.json",
  import.meta.url,
);
const target = new URL(
  "../apps/PointrPlayground/Sources/App/Model/TaxonomyProjection.swift",
  import.meta.url,
);
const projection = JSON.parse(await readFile(source, "utf8"));
if (!projection.version || !projection.properties)
  throw new Error("The taxonomy projection has no version or properties.");
const generated = `// Generated by scripts/sync-ios-taxonomy.mjs. Do not edit.
// Source: ${projection.source} (${projection.version}), via the web POI examples' projection.
import Foundation

enum TaxonomyProjection {
    static let version = "${projection.version}"
    static let json = #"""
${JSON.stringify(projection, null, 2)}
"""#
}
`;
if (process.argv.includes("--write")) {
  await writeFile(target, generated);
  console.log(`Wrote the taxonomy ${projection.version} projection for iOS.`);
} else if ((await readFile(target, "utf8").catch(() => "")) !== generated) {
  throw new Error("The iOS taxonomy projection is stale. Run with --write.");
} else {
  console.log(`iOS taxonomy projection matches ${projection.version}.`);
}
