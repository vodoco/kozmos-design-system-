/**
 * Generate the taxonomy's quick-access symbols as owned icons, for React and
 * for the Figma importer, from the SVGs the taxonomy publishes.
 *
 * The browse panel's tiles are the quick-access categories, and the product
 * draws each with the taxonomy's own symbol: a solid pictogram in the
 * category's colour. The Pointr Icon Library holds 1,176 stroke icons and none
 * of these, so the tiles carried lookalikes; these are the real ones, pinned to
 * one published version.
 *
 * An SVG is refused unless it is paths only, in one colour. The colour is
 * dropped, because a consumer tints the symbol. The artwork keeps its own
 * coordinates: only the viewBox changes, squared and widened so the symbol's
 * longer side spans 20 of 24, centred — the live area of a 24 icon in both
 * icon libraries.
 *
 * The published SVGs are kept under packages/icons/src/taxonomy/svg, named as
 * published, so a build needs no network and `--check` can hold the outputs to
 * them. `--fetch` downloads them again for the pinned version first.
 *
 * Writes:
 * - packages/icons/src/taxonomy/icons.generated.ts, the React components;
 * - the block between the generated markers in
 *   figma/foundations-importer/code.js, from which Curated Icons → Update
 *   draws an `Icon / taxonomy-*` component on the Icons page.
 *
 * Usage: node scripts/build-taxonomy-icons.mjs [--fetch] [--check]
 */
