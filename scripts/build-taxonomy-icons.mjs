function pascalCase(name) {
  return name
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");
}

function attributes(text) {
  const attrs = {};
  for (const [, key, value] of text.matchAll(/([\w:-]+)="([^"]*)"/g)) {
    attrs[key] = value;
  }
  return attrs;
}

/** Four decimals at most, and no trailing zeros: -6.4, not -6.400000000001. */
function number(value) {
  return String(Number(value.toFixed(4)));
}

/** The paths of a one-colour, paths-only SVG, and its viewBox squared to 24. */
function parse(svg, symbol) {
  const root = svg.match(/<svg\b([^>]*)>/);
  if (!root) throw new Error(`${symbol.file}: no <svg> element`);
  const rootAttrs = attributes(root[1]);
  const viewBox = (rootAttrs.viewBox || "")
    .trim()
    .split(/[\s,]+/)
    .map(Number);
  if (viewBox.length !== 4 || viewBox.some((n) => !Number.isFinite(n))) {
    throw new Error(`${symbol.file}: no usable viewBox`);
  }
  for (const key of Object.keys(rootAttrs)) {
    if (!["xmlns", "viewBox", "fill", "width", "height"].includes(key)) {
      throw new Error(
        `${symbol.file}: <svg> carries ${key}, which is not understood`,
      );
    }
  }

  const body = svg.slice(
    root.index + root[0].length,
    svg.lastIndexOf("</svg>"),
  );
  const paths = [];
  const colours = new Set();
  const rest = body.replace(/<(\w+)([^>]*?)\s*\/>/g, (_whole, tag, text) => {
    if (tag !== "path") {
      throw new Error(
        `${symbol.file}: <${tag}> is not a path; only paths are understood`,
      );
    }
    const attrs = attributes(text);
    for (const key of Object.keys(attrs)) {
      if (!["d", "fill", "fill-rule", "clip-rule"].includes(key)) {
        throw new Error(
          `${symbol.file}: a path carries ${key}, which is not understood`,
        );
      }
    }
    if (!attrs.d) throw new Error(`${symbol.file}: a path has no d`);
    colours.add((attrs.fill || rootAttrs.fill || "").toUpperCase());
    paths.push({
      d: attrs.d,
      ...(attrs["fill-rule"] ? { fillRule: attrs["fill-rule"] } : {}),
      ...(attrs["clip-rule"] ? { clipRule: attrs["clip-rule"] } : {}),
    });
    return "";
  });
  if (rest.trim()) {
    throw new Error(
      `${symbol.file}: content other than paths: ${rest.trim().slice(0, 60)}`,
    );
  }
  if (!paths.length) throw new Error(`${symbol.file}: no paths`);
  if (colours.size !== 1 || colours.has("") || colours.has("NONE")) {
    throw new Error(
      `${symbol.file}: not one solid colour (${[...colours].join(", ")})`,
    );
  }

  // The longer side spans 20 of 24, centred on both axes.
  const [x, y, width, height] = viewBox;
  const side = (Math.max(width, height) * 24) / 20;
  const square = [x + (width - side) / 2, y + (height - side) / 2, side, side]
    .map(number)
    .join(" ");
  return { paths, viewBox: square, colour: [...colours][0] };
}

async function fetchSymbols() {
  fs.mkdirSync(SVG_DIR, { recursive: true });
  for (const symbol of SYMBOLS) {
    const url = `${SOURCE_URL}/${symbol.file}.svg`;
    const response = await fetch(url);
    if (!response.ok)
      throw new Error(`${symbol.file}: ${response.status} from ${url}`);
    fs.writeFileSync(
      path.join(SVG_DIR, `${symbol.file}.svg`),
      await response.text(),
    );
    console.log(`  fetched ${symbol.file}.svg`);
  }
}

function escapeAttribute(value) {
  return value
    .replace(/&/g, "&amp;")
    .replace(/"/g, "&quot;")
    .replace(/</g, "&lt;");
}

/** The SVG the importer draws: 24 square, the paths in black, the tint the consumer's. */
function figmaSvg(symbol) {
  const paths = symbol.paths
    .map((p) => {
      const rules = [
        p.fillRule ? ` fill-rule="${p.fillRule}"` : "",
        p.clipRule ? ` clip-rule="${p.clipRule}"` : "",
      ].join("");
      return `<path${rules} d="${escapeAttribute(p.d)}" fill="#000000"/>`;
    })
    .join("");
  return `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="${symbol.viewBox}" fill="none">${paths}</svg>`;
}

function description(symbol) {
  return `${symbol.category}: the taxonomy's quick-access symbol for ${symbol.type} (${VERSION}).`;
}

async function format(text, parser) {
  const options = (await prettier.resolveConfig(PLUGIN)) || {};
  return prettier.format(text, { ...options, parser });
}

async function reactSource(symbols) {
  const body = symbols
    .map((symbol) => {
      const paths = symbol.paths
        .map(
          (p) =>
            `{ d: ${JSON.stringify(p.d)}${p.fillRule ? `, fillRule: ${JSON.stringify(p.fillRule)}` : ""}${p.clipRule ? `, clipRule: ${JSON.stringify(p.clipRule)}` : ""} },`,
        )
        .join("\n");
      return (
        `/** ${description(symbol)} Published as \`${symbol.file}.svg\`. */\n` +
        `export const ${pascalCase(symbol.name)} = createTaxonomyIcon(${JSON.stringify(pascalCase(symbol.name))}, ${JSON.stringify(symbol.viewBox)}, [\n${paths}\n]);`
      );
    })
    .join("\n\n");
  const header = `/**
 * Generated by scripts/build-taxonomy-icons.mjs — do not edit by hand.
 *
 * The taxonomy's own quick-access symbols at ${VERSION}, from
 * ${SOURCE_URL}, kept in their own coordinates
 * and drawn in the caller's colour.
 */
import { createTaxonomyIcon } from "./createTaxonomyIcon";

`;
  return format(header + body + "\n", "typescript");
}

async function pluginBlock(symbols) {
  const entries = symbols
    .map((symbol) => `  ${JSON.stringify(symbol.name)}: '${figmaSvg(symbol)}',`)
    .join("\n");
  const code = `const TAXONOMY_ICON_VERSION = ${JSON.stringify(VERSION)};
const TAXONOMY_ICON_SVGS = {
${entries}
};
`;
  const formatted = await format(code, "babel");
  return `${BEGIN}
// The taxonomy's quick-access symbols at ${VERSION}, squared to 24 and drawn
// in black for Curated Icons → Update to place on the Icons page. Edit
// scripts/build-taxonomy-icons.mjs and re-run it; never this block.
${formatted}${END}`;
}

if (args.has("--fetch")) await fetchSymbols();

const symbols = SYMBOLS.map((symbol) => {
  const file = path.join(SVG_DIR, `${symbol.file}.svg`);
  if (!fs.existsSync(file)) {
    throw new Error(
      `${path.relative(ROOT_DIR, file)} is missing; run with --fetch`,
    );
  }
  const parsed = parse(fs.readFileSync(file, "utf8"), symbol);
  return { ...symbol, ...parsed };
});

const react = await reactSource(symbols);
const block = await pluginBlock(symbols);
const plugin = fs.readFileSync(PLUGIN, "utf8");
const start = plugin.indexOf(BEGIN);
const end = plugin.indexOf(END);
if (start === -1 || end === -1 || end < start) {
  throw new Error(
    `${path.relative(ROOT_DIR, PLUGIN)} has no generated taxonomy block`,
  );
}
const nextPlugin =
  plugin.slice(0, start) + block + plugin.slice(end + END.length);

if (args.has("--check")) {
  const stale = [];
  if (
    !fs.existsSync(REACT_OUTPUT) ||
    fs.readFileSync(REACT_OUTPUT, "utf8") !== react
  ) {
    stale.push(path.relative(ROOT_DIR, REACT_OUTPUT));
  }
  if (nextPlugin !== plugin) stale.push(path.relative(ROOT_DIR, PLUGIN));
  if (stale.length) {
    console.error(
      `Out of date with packages/icons/src/taxonomy/svg: ${stale.join(", ")}. Run node scripts/build-taxonomy-icons.mjs.`,
    );
    process.exit(1);
  }
  console.log(
    `${symbols.length} taxonomy symbols at ${VERSION}: React and the importer match their SVGs.`,
  );
} else {
  fs.writeFileSync(REACT_OUTPUT, react);
  fs.writeFileSync(PLUGIN, nextPlugin);
  for (const symbol of symbols) {
    console.log(
      `  ${symbol.name.padEnd(44)} ${symbol.paths.length} path(s), viewBox ${symbol.viewBox}`,
    );
  }
  console.log(
    `\n${symbols.length} symbols -> ${path.relative(ROOT_DIR, REACT_OUTPUT)} and the importer`,
  );
}
