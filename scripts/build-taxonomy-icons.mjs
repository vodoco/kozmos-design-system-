const PLUGIN = path.join(ROOT_DIR, "figma/foundations-importer/code.js");
const BEGIN = "// <generated by scripts/build-taxonomy-icons.mjs>";
const END = "// </generated by scripts/build-taxonomy-icons.mjs>";

