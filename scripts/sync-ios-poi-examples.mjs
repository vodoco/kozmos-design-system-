// Run with node --import tsx scripts/sync-ios-poi-examples.mjs [--write].
// Reuses the versioned taxonomy adapter, not a second hand-maintained icon map.
import { readFile, writeFile } from "node:fs/promises";
import fixtures from "../packages/react/src/components/POIDetailPanel/POIDetailPanel.fixtures.ts";

const names = ["restaurant", "retail", "fitness", "entrance", "parking"];
const symbols = {
  rating: "star",
  accessibility: "figure.roll",
  crowd: "clock",
  dietary: "leaf",
  occupancy: "person.2",
  restriction: "lock",
};
const actionSymbols = {
  book: "calendar.badge.checkmark",
  call: "phone",
  website: "globe",
};
const examples = names.map((name) => ({
  id: name,
  title: name[0].toUpperCase() + name.slice(1),
  poi: fixtures[`${name}POI`],
  details: fixtures[`${name}Details`],
}));
examples.push({
  id: "full-fields",
  title: "All properties",
  poi: fixtures.restaurantPOI,
  details: fixtures.fullFieldDetails,
});
for (const example of examples) {
  const d = example.details;
  example.details = {
    ...d,
    summary: (d.summary ?? []).map((item) => ({
      ...item,
      systemImage: item.iconUrl ? undefined : symbols[item.kind],
    })),
    groups: d.groups ?? [],
    tags: d.tags ?? [],
    supplementaryActions: (d.supplementaryActions ?? []).map((item) => ({
      ...item,
      systemImage: actionSymbols[item.action],
    })),
  };
  if (d.issues?.length)
    throw new Error(`${example.id}: ${d.issues.join(", ")}`);
}
// A generated Swift literal avoids a second resource-loading/build-system path.
const source = `// Generated by scripts/sync-ios-poi-examples.mjs. Do not edit.\n// Source: Storybook POI fixtures and taxonomy 10.12.0 projection.\nimport Foundation\n\nenum POIExampleData {\n    static let json = #"""\n${JSON.stringify(examples, null, 2)}\n"""#\n}\n`;
const target = new URL(
  "../apps/Playground.swiftpm/Sources/App/Model/POIExampleData.swift",
  import.meta.url,
);
if (process.argv.includes("--write")) {
  await writeFile(target, source);
  console.log("Updated native POI fixtures from Storybook.");
} else if ((await readFile(target, "utf8")) !== source) {
  throw new Error("Native POI fixtures are stale. Run with --write.");
} else {
  console.log("Native POI fixtures match Storybook and taxonomy.");
}
