// Run with node scripts/sync-ios-quick-access.mjs [--write] [--fetch].
// The Pointr QA app's quick-access tiles search the SDK's places by words,
// because PTRPoi carries no taxonomy type. The words are the taxonomy's own:
// for each of a category's matchers, the matched type's displayName and its
// alsoKnownAs list (a boarding gate is "gate", "gates", "flight gate"; a
// restroom "toilet", "washroom", …), plus the category's name. This script
// derives them from the vendored quick-access file and the version-pinned
// taxonomy, into a small vendored JSON and a Swift literal the app reads.
// Default is a freshness check of the Swift against the JSON; --fetch reads
// the taxonomy from its published URL and rewrites the JSON; --write rewrites
// the Swift.
import { readFile, writeFile } from "node:fs/promises";

const version = "10.12.0";
const quickAccess = new URL(
  `../apps/PointrPlayground/Sources/App/Resources/QuickAccess/aviation-${version}.json`,
  import.meta.url,
);
const terms = new URL(
  `../apps/PointrPlayground/Sources/App/Resources/QuickAccess/aviation-terms-${version}.json`,
  import.meta.url,
);
const swift = new URL(
  "../apps/PointrPlayground/Sources/App/Model/QuickAccessTerms.swift",
  import.meta.url,
);
const taxonomyUrl = `https://pointrmapstorage.blob.core.windows.net/taxonomy/${version}/taxonomy.json`;

const words = (text) =>
  text
    .toLowerCase()
    .replace(/&/g, " and ")
    .split(/[^a-z0-9]+/)
    .filter(Boolean);

if (process.argv.includes("--fetch")) {
  const categories = JSON.parse(await readFile(quickAccess, "utf8"));
  const taxonomy = JSON.parse(await (await fetch(taxonomyUrl)).text());
  const byType = new Map();
  for (const entry of taxonomy.taxonomy) {
    byType.set(`${entry.mainType}/${entry.subType ?? ""}`, entry);
  }
  const derived = categories.map((category) => {
    const phrases = new Set([category.name.toLowerCase()]);
    for (const matcher of category.match ?? []) {
      // A matcher with service types names a service at a generic type (a
      // travel agency at an office): the service is the word, not every
      // office. A matcher on a type alone takes the type's name and aliases.
      if (matcher.serviceTypes?.length) {
        for (const service of matcher.serviceTypes) phrases.add(service.toLowerCase());
        continue;
      }
      if (!matcher.mainType) continue;
      const entry = byType.get(`${matcher.mainType}/${matcher.subType ?? ""}`);
      if (!entry) continue;
      phrases.add(entry.displayName.toLowerCase());
      for (const alias of entry.alsoKnownAs ?? []) phrases.add(alias.toLowerCase());
    }
    // Each phrase as it is, and its words: "flight gate" matches a place
    // named "Flight Gate B4" as a phrase and "Gate B4" by its word.
    const list = [...phrases].filter((p) => p.trim());
    return {
      name: category.name,
      source: category.match.map((m) => [m.mainType, m.subType].filter(Boolean).join("/")).filter(Boolean),
      phrases: list.sort(),
    };
  });
  await writeFile(
    terms,
    JSON.stringify({ version, source: taxonomyUrl, categories: derived }, null, 2) + "\n",
  );
  console.log(`Wrote the quick-access search words for ${derived.length} categories from taxonomy ${version}.`);
}

const data = JSON.parse(await readFile(terms, "utf8"));
const generated = `// Generated by scripts/sync-ios-quick-access.mjs. Do not edit.
// Source: ${data.source} (${data.version}) joined with quick-access/aviation.json:
// each category's matched types' displayName and alsoKnownAs, and its service types.
import Foundation

enum QuickAccessTerms {
    static let version = "${data.version}"
    static let json = #"""
${JSON.stringify(data, null, 2)}
"""#
}
`;
if (process.argv.includes("--write")) {
  await writeFile(swift, generated);
  console.log("Wrote QuickAccessTerms.swift.");
} else if ((await readFile(swift, "utf8").catch(() => "")) !== generated) {
  throw new Error("QuickAccessTerms.swift is stale. Run with --write.");
} else {
  console.log(`QuickAccessTerms.swift matches the terms for ${data.version}.`);
}
